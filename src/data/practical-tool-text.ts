export function getToolText(locale: ToolLocale = "ja") {
  return (text: string, ...values: (string | number)[]) => {
    const template = locale === "en" ? practicalToolEnglishText[text] ?? text : text;
    return template.replace(/\{(\d+)\}/g, (placeholder, index: string) => values[Number(index)] === undefined ? placeholder : String(values[Number(index)]));
  };
}
